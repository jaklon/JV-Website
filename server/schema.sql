CREATE TABLE IF NOT EXISTS albums (
 id CHAR(32) PRIMARY KEY, user_id CHAR(32) NOT NULL, title VARCHAR(120) NOT NULL,
 description TEXT NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS memories (
 id CHAR(32) PRIMARY KEY, user_id CHAR(32) NOT NULL, album_id CHAR(32) NULL,
 title VARCHAR(150) NOT NULL, date DATE NOT NULL, location VARCHAR(180) NOT NULL DEFAULT '',
 story TEXT NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id), FOREIGN KEY (album_id) REFERENCES albums(id) ON DELETE SET NULL,
 INDEX memories_date (date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS media (
 id CHAR(32) PRIMARY KEY, memory_id CHAR(32) NULL, user_id CHAR(32) NOT NULL,
 kind ENUM('image','video','audio') NOT NULL, name VARCHAR(255) NOT NULL,
 filename VARCHAR(100) NOT NULL, mime VARCHAR(100) NOT NULL, size BIGINT UNSIGNED NOT NULL,
 duration DECIMAL(12,3) NULL, position INT NOT NULL DEFAULT 0,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (memory_id) REFERENCES memories(id) ON DELETE CASCADE,
 FOREIGN KEY (user_id) REFERENCES users(id), INDEX media_order (memory_id,position)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS letters (
 id CHAR(32) PRIMARY KEY, user_id CHAR(32) NOT NULL, title VARCHAR(150) NOT NULL,
 body TEXT NOT NULL, status ENUM('draft','sent') NOT NULL DEFAULT 'draft', sent_at DATETIME NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, FOREIGN KEY (user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS important_dates (
 id CHAR(32) PRIMARY KEY, user_id CHAR(32) NOT NULL, title VARCHAR(120) NOT NULL,
 date DATE NOT NULL, recurring BOOLEAN NOT NULL DEFAULT TRUE, FOREIGN KEY (user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS movie_projects (
 id CHAR(32) PRIMARY KEY, user_id CHAR(32) NOT NULL, title VARCHAR(150) NOT NULL,
 recipe JSON NOT NULL, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
