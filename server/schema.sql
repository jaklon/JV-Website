CREATE TABLE IF NOT EXISTS users (
 id CHAR(32) PRIMARY KEY, google_sub VARCHAR(255) NOT NULL UNIQUE,
 email VARCHAR(255) NOT NULL UNIQUE, name VARCHAR(100) NOT NULL,
 picture TEXT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS relationship_settings (
 id TINYINT PRIMARY KEY, names VARCHAR(100) NOT NULL, since DATE NULL,
 tagline VARCHAR(250) NOT NULL, cover_id CHAR(32) NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
